type X = Partial<RuleDef>;
const r = (id: string, label: string, kind: RuleDef["kind"], def: RuleValue, section: SectionId, origin: RuleDef["origin"], x: X = {}): RuleDef => ({ id, label, kind, default: def, section, origin, ...x });
const b = (id: string, label: string, def: boolean, section: SectionId, origin: RuleDef["origin"], x: X = {}) => r(id, label, "bool", def, section, origin, x);
const n = (id: string, label: string, def: number, section: SectionId, origin: RuleDef["origin"], x: X = {}) => r(id, label, "int", def, section, origin, { min: 0, max: 999, ...x });

